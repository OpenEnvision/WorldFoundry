def extract(a, t, x_shape):
    b, *_ = t.shape
    out = a.gather(-1, t)
    return out.reshape(b, *((1,) * (len(x_shape) - 1)))


def cosine_beta_schedule(timesteps, s=0.008, dtype=torch.float32):
    """
    cosine schedule
    as proposed in https://openreview.net/forum?id=-NEXDKk8gZ
    """
    steps = timesteps + 1
    x = np.linspace(0, steps, steps)
    alphas_cumprod = np.cos(((x / steps) + s) / (1 + s) * np.pi * 0.5) ** 2
    alphas_cumprod = alphas_cumprod / alphas_cumprod[0]
    betas = 1 - (alphas_cumprod[1:] / alphas_cumprod[:-1])
    betas_clipped = np.clip(betas, a_min=0, a_max=0.999)
    return torch.tensor(betas_clipped, dtype=dtype)


def apply_conditioning(x, conditions, action_dim):
    for t, val in conditions.items():
        if isinstance(t, str):
            continue
        elif isinstance(t, int):
            if "agent_idx" in conditions:
                index = conditions["agent_idx"].long().unsqueeze(-1).repeat(1, 1, x.shape[-1] - action_dim)
                x[:, t, :, action_dim:].scatter_(1, index, val.clone().unsqueeze(1))
            else:
                x[:, t, :, action_dim:] = val.clone()
        elif isinstance(t, (tuple, list)):
            assert len(t) == 2, t
            if "agent_idx" in conditions:
                index = conditions["agent_idx"].long().unsqueeze(-1).repeat(1, t[1] - t[0], 1, x.shape[-1] - action_dim)
                x[:, t[0] : t[1], :, action_dim:].scatter_(2, index, val.clone().unsqueeze(2))
            else:
                x[:, t[0] : t[1], :, action_dim:] = val.clone()
        else:
            raise TypeError(type(t))
    return x


